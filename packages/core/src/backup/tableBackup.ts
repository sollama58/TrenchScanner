import { createHash } from "node:crypto";
import { gunzipSync, gzipSync } from "node:zlib";
import { Prisma, prisma } from "../db.js";
import type { Env } from "../config/env.js";
import { s3PutObject } from "../storage/s3.js";
import { createLogger } from "../logger.js";
import { WEEKLY_BACKUP_INTERVAL_MS, offsiteConfig } from "../curation/modelBackup.js";

const logger = createLogger("table-backup");

/**
 * Table backups: a weekly copy of the tables nothing else can rebuild, kept outside the live
 * tables (DataBackup) and copied to the model-backup bucket when one is set. Database audit
 * 2026-10-16 (J1), user decision: Render's point-in-time recovery covers the last 3-7 days and a
 * whole-database loss; this is the copy under the project's own control, for a deletion noticed
 * later than that window, and the one that can be downloaded and read without Render.
 *
 * What is in it: the users, their filters, Telegram chats, subscriptions and whitelist; the burn
 * events and burn-credit ledger; the trading wallets, bots, positions, orders and withdrawals;
 * the curator lanes (the recipes behind every seat) and the curated record (CuratedAlert, the
 * public track record). Not in it: Match and MatchArchive (the per-user alert history, 200 MB+,
 * rebuilt in spirit by the next scans), CandidateOutcome (the training set, 60-90 days deep and
 * regenerated by every scan) and the models (ModelBackup has those).
 *
 * The format is the tables' own rows as Postgres renders them to JSON (row_to_json), gzipped, so
 * a restore is json_populate_recordset straight back into the same table and needs no per-column
 * code here; `integrity` is a sha256 of the rest, so a truncated or edited file is refused.
 */

export const TABLE_BACKUP_FORMAT = "trenchscanner-table-backup";
export const TABLE_BACKUP_VERSION = 1;

export type TableBackupKind = "weekly" | "manual";

/** In restore order: a table after every table it points at. */
export const BACKED_UP_TABLES: readonly { name: string; key: string }[] = [
  { name: "User", key: "id" },
  { name: "Whitelist", key: "walletAddress" },
  { name: "Subscription", key: "id" },
  { name: "UserFilter", key: "id" },
  { name: "TelegramChat", key: "id" },
  { name: "BurnEvent", key: "id" },
  { name: "BurnCreditSettings", key: "id" },
  { name: "BurnCreditEntry", key: "id" },
  { name: "TradingWallet", key: "id" },
  { name: "TradingBot", key: "id" },
  { name: "TradingPosition", key: "id" },
  { name: "TradingOrder", key: "id" },
  { name: "TradingWithdrawal", key: "id" },
  { name: "CuratorLane", key: "id" },
  { name: "CuratedAlert", key: "id" },
];

/** Rows read (and written back) per statement: CuratedAlert is ~40 MB, the rest a few MB. */
const CHUNK_ROWS = 5_000;
/** Most bytes a backup may unzip to (see modelBackup.ts for why a gunzip needs a ceiling). */
const MAX_DECODED_BYTES = 1024 * 1024 * 1024;

export interface TableBackupTable {
  name: string;
  rows: unknown[];
}

export interface TableBackupPayload {
  format: typeof TABLE_BACKUP_FORMAT;
  version: number;
  createdAt: string;
  kind: TableBackupKind;
  note: string | null;
  tables: TableBackupTable[];
  /** sha256 (hex) of JSON.stringify of every field above, in this order. */
  integrity: string;
}

export class TableBackupError extends Error {}

const sha256Hex = (data: string | Uint8Array) => createHash("sha256").update(data).digest("hex");
const integrityOf = (body: Omit<TableBackupPayload, "integrity">) => sha256Hex(JSON.stringify(body));
const quote = (ident: string) => `"${ident.replace(/"/g, '""')}"`;

export function sealTableBackup(body: Omit<TableBackupPayload, "integrity">): TableBackupPayload {
  return { ...body, integrity: integrityOf(body) };
}

/**
 * Reads every backed-up table in one repeatable-read transaction, so a user created while the
 * read runs is either in the backup with their filters or not at all, never half. Each table is
 * read in key order, a chunk at a time, as Postgres' own JSON rendering of the row.
 */
export async function captureTableBackup(
  kind: TableBackupKind,
  note: string | null = null,
  now = new Date(),
): Promise<TableBackupPayload> {
  const tables = await prisma.$transaction(
    async (tx) => {
      const out: TableBackupTable[] = [];
      for (const { name, key } of BACKED_UP_TABLES) {
        const rows: unknown[] = [];
        let after: string | null = null;
        for (;;) {
          const chunk: { r: unknown; k: string }[] = await tx.$queryRawUnsafe(
            `SELECT row_to_json(t) AS r, t.${quote(key)}::text AS k FROM ${quote(name)} t
             WHERE $1::text IS NULL OR t.${quote(key)}::text > $1
             ORDER BY t.${quote(key)}::text LIMIT ${CHUNK_ROWS}`,
            after,
          );
          for (const row of chunk) rows.push(row.r);
          if (chunk.length < CHUNK_ROWS) break;
          after = chunk[chunk.length - 1]!.k;
        }
        out.push({ name, rows });
      }
      return out;
    },
    { isolationLevel: Prisma.TransactionIsolationLevel.RepeatableRead, maxWait: 30_000, timeout: 600_000 },
  );
  return sealTableBackup({
    format: TABLE_BACKUP_FORMAT,
    version: TABLE_BACKUP_VERSION,
    createdAt: now.toISOString(),
    kind,
    note,
    tables,
  });
}

export function encodeTableBackup(payload: TableBackupPayload): { data: Buffer; sha256: string } {
  const data = gzipSync(Buffer.from(JSON.stringify(payload), "utf8"));
  return { data, sha256: sha256Hex(data) };
}

/** Parses a backup file - gzipped (as downloaded) or plain JSON - and checks it end to end. */
export function decodeTableBackup(data: Uint8Array): TableBackupPayload {
  const buf = Buffer.from(data);
  let text: string;
  try {
    text = (
      buf[0] === 0x1f && buf[1] === 0x8b ? gunzipSync(buf, { maxOutputLength: MAX_DECODED_BYTES }) : buf
    ).toString("utf8");
  } catch (err) {
    if ((err as { code?: string }).code === "ERR_BUFFER_TOO_LARGE") {
      throw new TableBackupError("the file unzips to more than this build will read - it is not a backup");
    }
    throw new TableBackupError("the file is not a readable backup (gzip failed - truncated?)");
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    throw new TableBackupError("the file is not a backup (not JSON)");
  }
  return validateTableBackup(parsed);
}

const isObject = (v: unknown): v is Record<string, unknown> => typeof v === "object" && v !== null;

export function validateTableBackup(value: unknown): TableBackupPayload {
  if (!isObject(value) || value.format !== TABLE_BACKUP_FORMAT) {
    throw new TableBackupError("not a TrenchScanner table backup");
  }
  if (typeof value.version !== "number" || value.version > TABLE_BACKUP_VERSION) {
    throw new TableBackupError(
      `backup format version ${String(value.version)} is newer than this build reads`,
    );
  }
  const { integrity, ...rest } = value;
  if (
    typeof integrity !== "string" ||
    integrityOf(rest as Omit<TableBackupPayload, "integrity">) !== integrity
  ) {
    throw new TableBackupError("the backup's integrity check failed - the file was changed or cut short");
  }
  if (
    !Array.isArray(value.tables) ||
    !value.tables.every(
      (t) => isObject(t) && typeof t.name === "string" && Array.isArray(t.rows) && t.rows.every(isObject),
    )
  ) {
    throw new TableBackupError("the backup is malformed: tables");
  }
  return value as unknown as TableBackupPayload;
}

export interface TableBackupSummary {
  id: string;
  createdAt: Date;
  kind: string;
  note: string | null;
  tables: unknown;
  rowCount: number;
  sizeBytes: number;
  sha256: string;
  offsiteKey: string | null;
  offsiteAt: Date | null;
  offsiteError: string | null;
}

export const TABLE_BACKUP_SELECT = {
  id: true,
  createdAt: true,
  kind: true,
  note: true,
  tables: true,
  rowCount: true,
  sizeBytes: true,
  sha256: true,
  offsiteKey: true,
  offsiteAt: true,
  offsiteError: true,
} as const;

export async function storeTableBackup(payload: TableBackupPayload): Promise<TableBackupSummary> {
  const { data, sha256 } = encodeTableBackup(payload);
  const tables = payload.tables.map((t) => ({ name: t.name, rows: t.rows.length }));
  return prisma.dataBackup.create({
    data: {
      kind: payload.kind,
      note: payload.note,
      tables,
      rowCount: tables.reduce((n, t) => n + t.rows, 0),
      data,
      sizeBytes: data.length,
      sha256,
    },
    select: TABLE_BACKUP_SELECT,
  });
}

/** Reads the tables and stores the backup. */
export async function saveTableBackup(kind: TableBackupKind, note: string | null = null) {
  return storeTableBackup(await captureTableBackup(kind, note));
}

export async function listTableBackups(limit = 100): Promise<TableBackupSummary[]> {
  return prisma.dataBackup.findMany({
    orderBy: { createdAt: "desc" },
    take: limit,
    select: TABLE_BACKUP_SELECT,
  });
}

/** A stored backup's bytes, checked against the hash written with them. */
export async function loadTableBackupData(
  id: string,
): Promise<{ data: Buffer; row: TableBackupSummary } | null> {
  const row = await prisma.dataBackup.findUnique({
    where: { id },
    select: { ...TABLE_BACKUP_SELECT, data: true },
  });
  if (!row) return null;
  const { data, ...summary } = row;
  const buf = Buffer.from(data);
  if (sha256Hex(buf) !== row.sha256) {
    throw new TableBackupError("the stored backup does not match its checksum - it is damaged");
  }
  return { data: buf, row: summary };
}

export function tableBackupFileName(row: { createdAt: Date; kind: string; id: string }): string {
  const stamp = row.createdAt
    .toISOString()
    .replace(/[:]/g, "")
    .replace(/\.\d{3}Z$/, "Z");
  return `trenchscanner-tables-${stamp}-${row.kind}-${row.id}.json.gz`;
}

/** Whether the weekly table backup is due: none yet, or the newest is a week old. */
export async function weeklyTableBackupDue(now = new Date()): Promise<boolean> {
  const newest = await prisma.dataBackup.findFirst({
    where: { kind: "weekly" },
    orderBy: { createdAt: "desc" },
    select: { createdAt: true },
  });
  return !newest || now.getTime() - newest.createdAt.getTime() >= WEEKLY_BACKUP_INTERVAL_MS;
}

/** Keeps the newest `keep` backups of each kind. Off-site copies are the bucket's own business. */
export async function pruneTableBackups(keep: number): Promise<number> {
  let pruned = 0;
  for (const kind of ["weekly", "manual"] as const) {
    const surplus = await prisma.dataBackup.findMany({
      where: { kind },
      orderBy: { createdAt: "desc" },
      skip: keep,
      select: { id: true },
    });
    if (surplus.length === 0) continue;
    pruned += (await prisma.dataBackup.deleteMany({ where: { id: { in: surplus.map((r) => r.id) } } })).count;
  }
  return pruned;
}

/**
 * Copies backups that have no off-site copy yet to the model-backup bucket (MODEL_BACKUP_S3_*),
 * under table-backups/. A failure is recorded on the row and retried on the next pass.
 */
export async function uploadPendingTableBackups(
  env: Env,
  opts: { now?: Date; fetchImpl?: typeof fetch; limit?: number } = {},
): Promise<{ uploaded: number; failed: number; configured: boolean }> {
  const cfg = offsiteConfig(env);
  if (!cfg) return { uploaded: 0, failed: 0, configured: false };
  const now = opts.now ?? new Date();
  const pending = await prisma.dataBackup.findMany({
    where: { offsiteKey: null, createdAt: { gte: new Date(now.getTime() - 30 * 86_400_000) } },
    orderBy: [{ offsiteError: { sort: "asc", nulls: "first" } }, { createdAt: "asc" }],
    take: opts.limit ?? 3,
    select: { id: true },
  });
  let uploaded = 0;
  let failed = 0;
  for (const { id } of pending) {
    try {
      const loaded = await loadTableBackupData(id);
      if (!loaded) continue;
      const key = `${cfg.prefix}table-backups/${tableBackupFileName(loaded.row)}`;
      await s3PutObject(cfg, key, loaded.data, "application/gzip", opts.fetchImpl);
      await prisma.dataBackup.update({
        where: { id },
        data: { offsiteKey: key, offsiteAt: new Date(), offsiteError: null },
      });
      uploaded++;
    } catch (err) {
      failed++;
      await prisma.dataBackup
        .update({ where: { id }, data: { offsiteError: String(err).slice(0, 500) } })
        .catch(() => undefined);
    }
  }
  return { uploaded, failed, configured: true };
}

export interface TableRestoreResult {
  tables: { name: string; rows: number; inserted: number; skipped: number }[];
}

/**
 * Puts a backup's rows back, additively: a row whose key already exists is left as it is
 * (ON CONFLICT DO NOTHING), so running this against a live database brings back what was deleted
 * and overwrites nothing. A row whose parent is gone for good (a curated alert of a token the
 * cleanup has since swept) is skipped and counted, never the whole table. Tables the backup names
 * that this build does not back up are skipped. One transaction: all of it lands or none does.
 *
 * Run from a shell with `npm run backup:restore-tables -w @trenchscanner/worker -- <file>`; the
 * README's "Restore" section says when.
 */
export async function restoreTableBackup(payload: TableBackupPayload): Promise<TableRestoreResult> {
  const known = new Map(BACKED_UP_TABLES.map((t, i) => [t.name, i]));
  const ordered = payload.tables
    .filter((t) => known.has(t.name))
    .sort((a, b) => known.get(a.name)! - known.get(b.name)!);
  const skippedTables = payload.tables.filter((t) => !known.has(t.name)).map((t) => t.name);
  if (skippedTables.length > 0)
    logger.warn("table restore: skipping tables this build does not know", { skippedTables });

  return prisma.$transaction(
    async (tx) => {
      const result: TableRestoreResult = { tables: [] };
      for (const table of ordered) {
        const target = quote(table.name);
        const insertChunk = async (rows: unknown[]): Promise<number> => {
          const [row] = await tx.$queryRawUnsafe<{ n: bigint }[]>(
            `WITH ins AS (
               INSERT INTO ${target} SELECT * FROM json_populate_recordset(NULL::${target}, $1::json)
               ON CONFLICT DO NOTHING RETURNING 1)
             SELECT count(*)::bigint AS n FROM ins`,
            JSON.stringify(rows),
          );
          return Number(row?.n ?? 0);
        };
        let inserted = 0;
        let skipped = 0;
        for (let i = 0; i < table.rows.length; i += CHUNK_ROWS) {
          const chunk = table.rows.slice(i, i + CHUNK_ROWS);
          await tx.$executeRawUnsafe("SAVEPOINT chunk");
          try {
            inserted += await insertChunk(chunk);
            await tx.$executeRawUnsafe("RELEASE SAVEPOINT chunk");
          } catch (err) {
            await tx.$executeRawUnsafe("ROLLBACK TO SAVEPOINT chunk");
            if (!isForeignKeyError(err)) throw err;
            // One parent is missing somewhere in the chunk: find which rows, keep the rest.
            for (const one of chunk) {
              await tx.$executeRawUnsafe("SAVEPOINT row");
              try {
                inserted += await insertChunk([one]);
                await tx.$executeRawUnsafe("RELEASE SAVEPOINT row");
              } catch (inner) {
                await tx.$executeRawUnsafe("ROLLBACK TO SAVEPOINT row");
                if (!isForeignKeyError(inner)) throw inner;
                skipped++;
              }
            }
          }
        }
        result.tables.push({ name: table.name, rows: table.rows.length, inserted, skipped });
      }
      return result;
    },
    { maxWait: 30_000, timeout: 1_800_000 },
  );
}

function isForeignKeyError(err: unknown): boolean {
  const code =
    (err as { code?: string }).code ??
    (err as { meta?: { code?: string } }).meta?.code ??
    /code: "(\d{5})"/.exec(String(err))?.[1] ??
    "";
  return code === "23503" || /foreign key constraint/i.test(String(err));
}
